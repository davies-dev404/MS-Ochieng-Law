export const getBlogPosts = () => {
  if (typeof window !== 'undefined') {
    const localBlogs = localStorage.getItem('mso_blogs');
    if (localBlogs) {
      try {
        const parsed = JSON.parse(localBlogs);
        // Combine local blogs with default blogs (local blogs first)
        return [...parsed, ...defaultBlogPosts];
      } catch (e) {
        console.error("Failed to parse local blogs", e);
      }
    }
  }
  return defaultBlogPosts;
};

export const saveBlogPost = (post) => {
  if (typeof window !== 'undefined') {
    const localBlogs = localStorage.getItem('mso_blogs');
    let blogs = [];
    if (localBlogs) {
      try {
        blogs = JSON.parse(localBlogs);
      } catch (e) {}
    }
    blogs.unshift(post);
    localStorage.setItem('mso_blogs', JSON.stringify(blogs));
  }
};

export const updateBlogPost = (updatedPost) => {
  if (typeof window !== 'undefined') {
    const localBlogs = localStorage.getItem('mso_blogs');
    if (localBlogs) {
      try {
        let blogs = JSON.parse(localBlogs);
        const index = blogs.findIndex(b => b.id === updatedPost.id);
        if (index !== -1) {
          blogs[index] = updatedPost;
          localStorage.setItem('mso_blogs', JSON.stringify(blogs));
          return true;
        }
      } catch (e) {
        console.error("Failed to update blog", e);
      }
    }
  }
  return false;
};

export const deleteBlogPost = (id) => {
  if (typeof window !== 'undefined') {
    const localBlogs = localStorage.getItem('mso_blogs');
    if (localBlogs) {
      try {
        let blogs = JSON.parse(localBlogs);
        blogs = blogs.filter(b => b.id !== id);
        localStorage.setItem('mso_blogs', JSON.stringify(blogs));
        return true;
      } catch (e) {
        console.error("Failed to delete blog", e);
      }
    }
  }
  return false;
};

